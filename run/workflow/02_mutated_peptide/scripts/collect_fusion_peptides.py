def generate_nmer_peptides(flanked_mutated_protein_sequence, nmer_length=9):
    """
    with provided flanked mutated peptide, do sliding window to generate ideal length of n_mer peptides

    return a list of nmer peptides (or an empty list)
    """
    nmers = []
    if flanked_mutated_protein_sequence != None: 
    #if position_start is not None and position_end is not None:
        for i in range(len(flanked_mutated_protein_sequence)):
            if i >= 0 and i + nmer_length <= len(flanked_mutated_protein_sequence):
                nmers.append(''.join(flanked_mutated_protein_sequence[i:i + nmer_length]))
    return nmers



def generate_flanked_fasta(df, flanked_output_path, min_alt_read_base=0):
    """
    Generate a FASTA file for sequences from the 'fusion_amino_acid_sequence' column.
    
    Arguments:
    df (DataFrame): Input DataFrame containing mutation data.
    flanked_output_path (str): File path to save FASTA for 'fusion_amino_acid_sequence'.
    min_alt_read_base (int): Minimum fusion_read_support for filtering rows.
    """

    filtered_df = df[df['fusion_read_support'] >= min_alt_read_base]

    with open(flanked_output_path, 'w') as flanked_fasta_file:
        for index, row in filtered_df.iterrows():
            sequence = row.get('fusion_amino_acid_sequence', None)
            
            if pd.notna(sequence) and sequence:
                fasta_id = row.get('ID', '')
                flanked_fasta_file.write(f">{fasta_id}\n")
                flanked_fasta_file.write(f"{sequence}\n")
    
    print(f"FASTA file for 'flanked_mutated_protein_sequence' written to: {flanked_output_path}")

def generate_nmer_fasta(df, nmer_output_path, min_alt_read_base=0, nmer_length=9):
    """
    Generate a FASTA file for peptides with 'nmer'. First 'nmer' needs to be generated by longer sequence.
    
    Arguments:
    df (DataFrame): Input DataFrame containing mutation data.
    nmer_output_path (str): File path to save FASTA for 'nmer' peptides.
    min_alt_read_base (int): Minimum alt_read_base_counts for filtering rows.
    """
    filtered_df = df[df['fusion_read_support'] >= min_alt_read_base]
    
    with open(nmer_output_path, 'w') as nmer_fasta_file:
        for index, row in filtered_df.iterrows():
            sequence = row.get('fusion_amino_acid_sequence', None)
            nmer_list = generate_nmer_peptides(sequence, nmer_length)
            fasta_id = row.get('ID', '')

            if nmer_list and isinstance(nmer_list, list):
                try:
                    for peptide in nmer_list:
                        nmer_fasta_file.write(f">{fasta_id}\n")
                        nmer_fasta_file.write(f"{peptide}\n")
                except Exception as e:
                    print(f"Error processing 'nmer' in row {index}: {e}")
            


    print(f"FASTA file for 'nmer' peptides written to: {nmer_output_path}")


